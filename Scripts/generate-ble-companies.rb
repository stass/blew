#!/usr/bin/env ruby
# frozen_string_literal: true

# generate-ble-companies.rb <sig-dir> <output-file>
#
# Reads assigned_numbers/company_identifiers/company_identifiers.yaml from
# <sig-dir> (the Bluetooth SIG Assigned Numbers, section 7.1) and writes a
# Swift source file with one static dictionary, company identifier to company
# name, into <output-file>.

require "yaml"

abort "Usage: generate-ble-companies.rb <sig-dir> <output-file>" unless ARGV.length == 2

sig_dir     = ARGV[0]
output_file = ARGV[1]

def generation_error(message)
  abort "generate-ble-companies.rb: #{message}"
end

path = File.join(sig_dir, "assigned_numbers", "company_identifiers", "company_identifiers.yaml")
unless File.file?(path)
  generation_error "#{path} not found. The Bluetooth SIG Assigned Numbers are a git " \
                   "submodule: run `git submodule update --init` in the blew checkout."
end

document = YAML.safe_load(File.read(path, encoding: "utf-8"))
entries = document.is_a?(Hash) ? document["company_identifiers"] : nil
generation_error "#{path} has no company identifiers" unless entries.is_a?(Array) && !entries.empty?

companies = {}
entries.each do |entry|
  generation_error "#{path}: entry #{entry.inspect} is not a value and a name" unless entry.is_a?(Hash)
  value = entry["value"]
  name = entry["name"]
  unless value.is_a?(Integer) && value.between?(0, 0xFFFF)
    generation_error "#{path}: company identifier #{value.inspect} is not a 16-bit integer"
  end
  unless name.is_a?(String) && !name.strip.empty?
    generation_error "#{path}: company identifier 0x#{format('%04X', value)} has no name"
  end
  if companies.key?(value)
    generation_error "#{path}: company identifier 0x#{format('%04X', value)} is listed twice"
  end
  companies[value] = name.strip
end

# A Swift string literal holding `str`: backslash and quote escaped, and every
# character outside printable ASCII except letters written as \u{...}, so the
# generated file stays plain text whatever the YAML holds.
def swift_literal(str)
  body = str.each_char.map do |c|
    case c
    when "\\" then "\\\\"
    when '"' then '\\"'
    when /[[:print:]]/ then c.ord < 0x80 || c =~ /\p{L}/ ? c : format("\\u{%X}", c.ord)
    else format("\\u{%X}", c.ord)
    end
  end.join
  "\"#{body}\""
end

lines = companies.sort.map { |value, name| format("        0x%04X: %s", value, swift_literal(name)) }

output = <<~SWIFT
  // CompanyNames.generated.swift
  // Auto-generated by Scripts/generate-ble-companies.rb from the Bluetooth SIG
  // Assigned Numbers (assigned_numbers/company_identifiers/company_identifiers.yaml).
  // Do not edit manually -- rebuild to regenerate.

  enum CompanyNameData {
      static let names: [UInt16: String] = [
  #{lines.join(",\n")}
      ]
  }
SWIFT

File.write(output_file, output)
$stderr.puts "Generated #{output_file} (#{companies.length} company identifiers)"
